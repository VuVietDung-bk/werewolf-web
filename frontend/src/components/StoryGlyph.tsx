function PixelGlyph({ name, size }: { name: SpriteName; size: number }) {
  return <svg className={`story-glyph story-glyph-${name}`} width={size} height={size}
    viewBox="0 0 24 24" shapeRendering="crispEdges" aria-hidden="true" focusable="false">
    {sprites[name].flatMap((row, y) => [...row].map((pixel, x) => pixel === '.' ? null
      : <rect key={`${x}:${y}`} x={x * 2} y={y * 2} width="2" height="2"
        fill={colors[name][Number(pixel) - 1]} />))}
  </svg>
}

export function RequestGlyph({ status, size = 24 }: { status: string; size?: number }) {
  const known: RequestStatus[] = ['pending', 'in_review', 'accepted', 'rejected', 'withdrawn']
  const safe = known.includes(status as RequestStatus) ? status as RequestStatus : 'pending'
  return <PixelGlyph name={`request-${safe}`} size={size} />
}

export function NoticeGlyph({ kind, size = 24 }: { kind: NoticeKind; size?: number }) {
  return <PixelGlyph name={`notice-${kind}`} size={size} />
}
